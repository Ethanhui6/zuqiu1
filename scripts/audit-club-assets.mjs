import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = JSON.parse(await fs.readFile(path.join(root, 'data', 'clubs.json'), 'utf8'));
const expansion = JSON.parse(await fs.readFile(path.join(root, 'data', 'world-expansion.json'), 'utf8'));
const clubs = [...base.clubs, ...expansion.clubs];
const { CLUB_CRESTS } = await import(pathToFileURL(path.join(root, 'src', 'data', 'clubCrests.js')).href);
const checked = await Promise.all(clubs.map(async club => {
  const crest = club.crest || club.crestPath || CLUB_CRESTS[club.id]?.path || null;
  const file = crest && path.join(root, crest.replace(/^\.\//, ''));
  const exists = Boolean(file) && await fs.access(file).then(() => true).catch(() => false);
  const source = exists && path.extname(file).toLowerCase() === '.svg' ? await fs.readFile(file, 'utf8') : '';
  return { club, crest, exists, source };
}));
const missing = checked.filter(item => !item.crest);
const broken = checked.filter(item => item.crest && !item.exists);
const fallback = checked.filter(item => item.club.crestSource?.generated);
const duplicatePaths = checked.filter((item, index) => checked.findIndex(other => other.crest === item.crest) !== index);
const remote = checked.filter(item => /(?:href|src)\s*=\s*["']https?:/i.test(item.source));
const letterPlaceholders = fallback.filter(item => /<text\b/i.test(item.source));
const watermarked = checked.filter(item => /watermark|googleusercontent|gstatic/i.test(item.source));
const hash = value => [...value].reduce((total, char) => Math.imul(total ^ char.codePointAt(0), 16777619) >>> 0, 2166136261);
const sample = [...checked].sort((a, b) => hash(`${a.club.id}|phase21`) - hash(`${b.club.id}|phase21`)).slice(0, 100);
const incorrect = sample.filter(item => !item.exists || !item.club.crestSource?.sourcePage || path.basename(item.crest, path.extname(item.crest)).toLowerCase() !== item.club.id.toLowerCase() || duplicatePaths.includes(item));
const result = { status: 'PASS', total: checked.length, real: checked.length - fallback.length, fallback: fallback.length, missing: missing.length, broken: broken.length, sampled: sample.length, incorrect: incorrect.length, duplicatePaths: duplicatePaths.length, remote: remote.length, letterPlaceholders: letterPlaceholders.length, watermarked: watermarked.length };
if ([missing, broken, incorrect, duplicatePaths, remote, letterPlaceholders, watermarked].some(items => items.length)) throw new Error(JSON.stringify({ ...result, status: 'FAIL' }));
console.log(JSON.stringify(result));
